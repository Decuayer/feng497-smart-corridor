#!/usr/bin/env python3
"""Compute the PLACEHOLDER corridor routes for osm_alsancak_v0.

For each direction, finds the shortest route that passes through the six agent
traffic lights of ``osm_alsancak_v0`` (ai/configs/fixtures.yaml) in corridor
order. It chooses one controlled link (incoming edge -> outgoing edge) per light
with dynamic programming over the link choices and joins them with shortest
paths. The result is written to
ai/sim_fixtures/osm_alsancak_v0/corridor.yaml (committed, used by the
corridor demand scenario and the emergency-corridor KPI).

ASSUMPTION: the true pilot corridor geometry is defined by Öykü (simulation/).
This route only exists so ai/ can test the emergency corridor on a placeholder.

Usage: python ai/scripts/build_osm_corridor.py
"""

from __future__ import annotations

from pathlib import Path

import sumolib
import yaml

from corridor_ai.common.paths import FIXTURE_DIR
from corridor_ai.common.registry import load_fixture

OUT = FIXTURE_DIR / "osm_alsancak_v0" / "corridor.yaml"


def _links(net, tls_id: str) -> list[tuple[str, str]]:
    return sorted(
        {
            (i.getEdge().getID(), o.getEdge().getID())
            for i, o, _ in net.getTLS(tls_id).getConnections()
        }
    )


def _shortest(net, a: str, b: str):
    if a == b:
        return [a], 0.0
    path, cost = net.getShortestPath(net.getEdge(a), net.getEdge(b))
    return ([e.getID() for e in path], cost) if path else (None, float("inf"))


def corridor_route(net, tls_order: list[str]) -> tuple[float, list[str]]:
    length = {e.getID(): e.getLength() for e in net.getEdges()}
    best = {
        link: (length[link[0]] + length[link[1]], list(link)) for link in _links(net, tls_order[0])
    }
    for tls in tls_order[1:]:
        nxt = {}
        for link in _links(net, tls):
            cand = None
            for prev, (cost, path) in best.items():
                seg, seg_cost = _shortest(net, prev[1], link[0])
                if seg is None:
                    continue
                total = cost + seg_cost - length[prev[1]] + length[link[1]]
                if cand is None or total < cand[0]:
                    cand = (total, path + seg[1:] + [link[1]])
            if cand:
                nxt[link] = cand
        if not nxt:
            raise RuntimeError(f"no route reaches {tls}")
        best = nxt
    return min(best.values())


def lights_on_route(net, edges: list[str]) -> list[str]:
    seq: list[str] = []
    for a, b in zip(edges, edges[1:], strict=False):
        for conn in net.getEdge(a).getOutgoing().get(net.getEdge(b), []):
            tls = conn.getTLSID()
            if tls and (not seq or seq[-1] != tls):
                seq.append(tls)
    return seq


def main() -> None:
    fx = load_fixture("osm_alsancak_v0")
    net = sumolib.net.readNet(str(fx.net), withPrograms=True)
    names = {tls: cid for cid, tls in fx.agents.items()}
    order = list(fx.agents.values())
    routes = {}
    for name, tls_order in (("alsancak_to_konak", order), ("konak_to_alsancak", order[::-1])):
        cost, edges = corridor_route(net, tls_order)
        lights = lights_on_route(net, edges)
        routes[name] = {
            "length_m": round(cost, 1),
            "agents_in_order": [names[t] for t in lights if t in names],
            "background_lights": [t for t in lights if t not in names],
            "edges": edges,
        }
        print(f"{name}: {cost:.0f} m, {len(edges)} edges, {len(lights)} lights")
    header = (
        "# PLACEHOLDER corridor routes for osm_alsancak_v0 (generated by\n"
        "# ai/scripts/build_osm_corridor.py - do not edit by hand).\n"
        "# Shortest routes through the six agent lights in corridor order.\n"
        "# ASSUMPTION: the real pilot corridor is defined by Öykü in simulation/.\n"
    )
    Path(OUT).write_text(header + yaml.safe_dump({"routes": routes}, sort_keys=False), "utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
